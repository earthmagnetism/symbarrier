def table(head, rows):
    w("| " + " | ".join(head) + " |")
    lens = [min(max([len(str(h))] + [len(str(r[i])) for r in rows]), 30) for i, h in enumerate(head)]
    w("|" + "|".join("-" * max(3, n) for n in lens) + "|")
    for r in rows:
        w("| " + " | ".join(str(c) for c in r) + " |")
    w("")


def spacing(tec):
    c, t, P = read_tecplot(tec)
    wt = node_weights(c, t)
    return max(rms_angle_deg(P[i], P[i + 1], wt) for i in range(len(P) - 1))


